import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
test('startup shows real activity and a terminal error without implying backup completion', () => {
  const elements = Object.fromEntries(['status','hint','elapsed','main'].map(id => [id, {textContent:'',setAttribute(name,value){this[name]=value;}}]));
  const intervals = new Map(), cleared = new Set();
  let now = 0, nextTimer = 1;
  const layers = [{style:{}}, {style:{}}];
  const stage = {classList:{add(){}}};
  const body = {dataset:{}};
  const window = {};
  const selectors = {'main':elements.main,'.sprite-layer.layer-a':layers[0],'.sprite-layer.layer-b':layers[1],'.avatar-stage':stage};
  const document = {body,getElementById:id=>elements[id],querySelector:selector=>selectors[selector] ?? null};
  vm.runInNewContext(readFileSync(new URL('../shell/startup.js',import.meta.url),'utf8'), {window,document,Date:{now:()=>now},setTimeout:()=>0,setInterval:fn=>{const id=nextTimer++;intervals.set(id,fn);return id;},clearInterval:id=>{cleared.add(id);}});
  const tick = () => {for (const [id,fn] of intervals) if (!cleared.has(id)) fn();};
  window.biankStartup.update({phase:'snapshot',detail:'Verificando tus datos · 120 archivos revisados'});
  assert.match(elements.hint.textContent,/Asegurando tus datos/);
  assert.doesNotMatch(elements.hint.textContent,/completad|respaldad/i);
  assert.equal(elements.status.textContent,'Verificando tus datos · 120 archivos revisados');
  now=14000;tick();assert.equal(elements.elapsed.textContent,'');
  now=82000;tick();assert.equal(elements.elapsed.textContent,'Iniciando servicios locales…');
  assert.doesNotMatch(elements.elapsed.textContent,/\d/);
  window.biankStartup.update({phase:'profiles',detail:'Preparando tu perfil y tus datos…'});
  assert.doesNotMatch(elements.hint.textContent,/respaldar/);
  window.biankStartup.update({phase:'error',detail:'No se pudo leer el perfil'});
  assert.equal(body.dataset.state,'error');assert.equal(elements.main['aria-busy'],'false');
  window.biankStartup.update({phase:'ready',detail:'Abriendo Biank…'});
  assert.equal(elements.status.textContent,'No se pudo leer el perfil');tick();assert.equal(cleared.size,intervals.size);
});
